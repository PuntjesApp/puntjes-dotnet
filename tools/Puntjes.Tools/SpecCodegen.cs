using System.Globalization;
using System.Text;
using System.Text.Json;

namespace Puntjes.Tools;

/// <summary>Writes the C# the thin layer reads from spec/api.json: the error codes and the operations sent without a token.</summary>
public static class SpecCodegen
{
    private static readonly string[] Methods = ["get", "put", "post", "delete", "patch", "head", "options"];

    public static IReadOnlyList<(string Code, int Status)> ErrorCodes(JsonDocument spec)
    {
        var codes = new SortedDictionary<string, int>(StringComparer.Ordinal);
        Walk(spec.RootElement, codes);

        return codes.Select(pair => (pair.Key, pair.Value)).ToList();
    }

    public static IReadOnlyList<string> PublicOperations(JsonDocument spec)
    {
        var operations = new List<string>();
        if (!spec.RootElement.TryGetProperty("paths", out var paths))
        {
            return operations;
        }

        foreach (var path in paths.EnumerateObject())
        {
            foreach (var operation in path.Value.EnumerateObject().Where(o => Methods.Contains(o.Name)))
            {
                if (operation.Value.TryGetProperty("security", out var security)
                    && security.ValueKind == JsonValueKind.Array
                    && security.GetArrayLength() == 0)
                {
                    operations.Add($"{operation.Name.ToUpperInvariant()} {path.Name}");
                }
            }
        }

        operations.Sort(StringComparer.Ordinal);

        return operations;
    }

    public static string RenderErrorCode(IReadOnlyList<(string Code, int Status)> codes)
    {
        var members = Lines(codes, c => $"    {Member(c.Code)},");
        var wire = Lines(codes, c => $"        ErrorCode.{Member(c.Code)} => \"{c.Code}\",");
        var statuses = Lines(codes, c => $"        ErrorCode.{Member(c.Code)} => {c.Status},");
        var parse = Lines(codes, c => $"            \"{c.Code}\" => ErrorCode.{Member(c.Code)},");

        return $$"""
            // <auto-generated/>
            #nullable enable
            namespace Puntjes.Sdk.Generated.Errors;

            /// <summary>Every error code the API documents, generated from the x-error-codes of spec/api.json. Do not edit.</summary>
            public enum ErrorCode
            {
            {{members}}
            }

            /// <summary>The wire form and the HTTP status of each <see cref="ErrorCode"/>. Generated. Do not edit.</summary>
            public static class ErrorCodes
            {
                public static string ToWire(this ErrorCode code) => code switch
                {
            {{wire}}
                    _ => throw new ArgumentOutOfRangeException(nameof(code)),
                };

                public static int Status(this ErrorCode code) => code switch
                {
            {{statuses}}
                    _ => throw new ArgumentOutOfRangeException(nameof(code)),
                };

                public static bool TryParse(string? wire, out ErrorCode code)
                {
                    ErrorCode? found = wire switch
                    {
            {{parse}}
                        _ => null,
                    };
                    code = found.GetValueOrDefault();

                    return found.HasValue;
                }
            }

            """;
    }

    public static string RenderPublicOperations(IReadOnlyList<string> operations)
    {
        var list = Lines(operations, o => $"        \"{o}\",");

        return $$"""
            // <auto-generated/>
            #nullable enable
            namespace Puntjes.Sdk.Generated.Security;

            /// <summary>The operations whose security in spec/api.json is empty, so they are sent without a token. Generated. Do not edit.</summary>
            public static class PublicOperations
            {
                public static readonly IReadOnlyList<string> Operations =
                [
            {{list}}
                ];

                public static bool Matches(string method, string path)
                {
                    var segments = path.Split('/');
                    foreach (var operation in Operations)
                    {
                        var parts = operation.Split(' ', 2);
                        if (string.Equals(method, parts[0], StringComparison.OrdinalIgnoreCase) && Fits(parts[1].Split('/'), segments))
                        {
                            return true;
                        }
                    }

                    return false;
                }

                private static bool Fits(string[] template, string[] path)
                {
                    if (template.Length != path.Length)
                    {
                        return false;
                    }

                    for (var i = 0; i < template.Length; i++)
                    {
                        var isParameter = template[i].StartsWith('{') && template[i].EndsWith('}');
                        if (isParameter ? path[i].Length == 0 : path[i] != template[i])
                        {
                            return false;
                        }
                    }

                    return true;
                }
            }

            """;
    }

    private static void Walk(JsonElement node, SortedDictionary<string, int> codes)
    {
        if (node.ValueKind == JsonValueKind.Array)
        {
            foreach (var child in node.EnumerateArray())
            {
                Walk(child, codes);
            }

            return;
        }

        if (node.ValueKind != JsonValueKind.Object)
        {
            return;
        }

        if (node.TryGetProperty("x-error-codes", out var entries))
        {
            foreach (var entry in entries.EnumerateArray())
            {
                var code = entry.GetProperty("code").GetString()!;
                var status = entry.GetProperty("status").GetInt32();
                if (codes.TryGetValue(code, out var known) && known != status)
                {
                    throw new InvalidOperationException($"{code} has two statuses, {known} and {status}.");
                }

                codes[code] = status;
            }
        }

        foreach (var property in node.EnumerateObject())
        {
            Walk(property.Value, codes);
        }
    }

    private static string Member(string code) =>
        string.Concat(code.Split('_').Select(word => CultureInfo.InvariantCulture.TextInfo.ToTitleCase(word.ToLowerInvariant())));

    private static string Lines<T>(IEnumerable<T> items, Func<T, string> line) =>
        string.Join("\n", items.Select(line));
}
